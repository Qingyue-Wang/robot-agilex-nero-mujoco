"""Fixed-base AgileX Nero arm primitive (MuJoCo Native backend).

The sim layer (``sim/bridge/bridge_node.py``) owns the physics loop AND the
ROS topics. This primitive is the thin Robonix boot-layer wrapper that:

    on_init       — validate config, cache for activate.
    on_activate   — spawn ``sim/start.sh``, wait for the first
                    ``/joint_states`` as proof the sim is up, then declare the
                    three ROS 2 data topics on Atlas (joint_states /
                    joint_command / end_pose). ``arm/driver`` is auto-declared
                    by the framework lifecycle servicer.
    on_deactivate — kill the sim subprocess (process group).
    on_shutdown   — last-chance kill (idempotent with on_deactivate).

The rpc capabilities (status / set_enabled / emergency_stop / move_home /
follow_joint_trajectory) are exposed as MCP tools that call the bridge's ROS
services / actions, so plans gate, recover and move the simulated arm through
the same capability graph they use for a real arm.

Config (from the deploy manifest's ``primitive[].config`` block, delivered via
``Driver(CMD_INIT, config_json)``):

    joint_states_topic       default "/joint_states"
    joint_command_topic      default "/joint_command"
    end_pose_topic           default "/feedback/tcp_pose"
    object_pose_topic        default "/feedback/object_pose"
    arm_controller_action    default "/arm_controller/follow_joint_trajectory"
    gripper_controller_action default "/gripper_controller/follow_joint_trajectory"
    sentinel_timeout_s       default 30.0
    viewer                   default false      — open a mujoco.viewer window
    sim_python               default ""         — override the sim interpreter
                             (passed through as NERO_PYTHON to sim/start.sh)
    move_home_on_activate    default true       — call /move_home once right
                             after activation, so the arm starts at
                             NeroMujocoController.move_home()'s target pose
                             instead of the sim's raw zero qpos.
"""
